        //    synchronisation. Aucun de ces raffinements n'est relu par DBAL (ni classe
        //    d'opérateurs, ni sens de tri, ni placement des nuls, ni `NULLS NOT
        //    DISTINCT`), donc le schéma reste vu comme synchronisé.
        // ------------------------------------------------------------------

        // `varchar_pattern_ops` : sans cet opérateur, un index btree sur une base qui
        // n'est pas en collation `C` — la nôtre est en ICU fr-FR — **ne sert pas** les
        // `LIKE 'BOURRACHE%'` de la recherche de rattachement. L'index existerait et
        // resterait inutilisé, ce qui est le pire des deux mondes.
        $this->addSql('DROP INDEX idx_tree_person_search');
        $this->addSql('CREATE INDEX idx_tree_person_search ON tree_person (search_key varchar_pattern_ops)');

