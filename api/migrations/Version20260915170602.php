        $this->addSql('CREATE INDEX idx_mbr_invitation_status ON mbr_invitation (status, created_at DESC)');
        $this->addSql('DROP INDEX idx_mbr_claim_invitation');
        $this->addSql('CREATE INDEX idx_mbr_claim_invitation ON mbr_claim_attempt (invitation_id, occurred_at DESC)');
        $this->addSql('DROP INDEX idx_mbr_claim_ip');
        $this->addSql('CREATE INDEX idx_mbr_claim_ip ON mbr_claim_attempt (ip, occurred_at DESC)');
