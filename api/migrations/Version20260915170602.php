        // est l'ordre attendu à l'écran. La clause est écrite explicitement parce que le
        // modèle la nomme, mais `NULLS LAST` **est déjà le défaut d'un tri ascendant**
        // sous PostgreSQL : `pg_get_indexdef` ne la réaffiche pas, et son absence dans
        // un `\d tree_fact` ne veut pas dire qu'elle a été perdue.
        $this->addSql('DROP INDEX idx_tree_fact_person');
        $this->addSql('CREATE INDEX idx_tree_fact_person ON tree_fact (person_id, happened_min NULLS LAST, sort_order)');

