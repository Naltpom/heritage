        // 3. Raffinements d'index hors de portée du mapping Doctrine.
        //
        //    Chaque entrée est un `DROP` suivi d'un `CREATE` : sur une base vierge
        //    l'index est vide, l'opération ne coûte rien, et la section 1 reste ainsi
