 * naissent d'une détection qui relit l'arbre — elles portent **ce qu'on en a fait**.
 *
 * ## L'index unique est le mécanisme, pas une précaution
 *
 * `uniq_qst_question_lacune (destinataire_user_id, signature)`, où `signature` vaut
 * `sha256(nature : sujet_kind : sujet_id)` : une lacune, un destinataire, une ligne.
 *
 * C'est ce qui rend la détection **idempotente sans qu'aucun service ait à s'en
 * souvenir**. On la rejoue à chaque chargement de page ; elle retombe sur les mêmes
 * signatures, retrouve les lignes, ne repose rien. Un « je ne sais pas » répondu hier
 * survit donc à mille détections, par construction et non par vigilance.
 *
 * Le destinataire est la **seconde colonne de l'index**, et non un ingrédient du haché.
 * La différence compte : mêlé à la signature, il aurait rendu impossible la seule
 * requête transversale du module — « à qui d'autre a-t-on posé cette lacune, et qu'en
 * ont-ils dit ? », qu'on pose avant d'en interroger un de plus.
 *
 * ## Les deux `CHECK`, et ce que chacun attrape
 *
 * Elles sont des **équivalences** (`=` entre deux prédicats), pas des implications.
 * Une implication simple laisserait passer la moitié muette du défaut :
 *
 * - `ck_qst_question_differee` : `relancer_apres` est renseigné **si et seulement si**
 *   l'état est `differee`. Sans le « seulement si », une question fermée pourrait
 *   garder une date de relance d'une vie antérieure — invisible, sauf le jour où
 *   quelqu'un écrit une requête de réveil qui la ramasse.
 * - `ck_qst_question_repondue` : `repondu_le` est renseigné **si et seulement si**
 *   l'état est `inconnue` ou `repondue`. « Je ne sais pas » est une réponse : sans son
 *   horodatage, rien ne distinguerait « personne n'a jamais regardé » de « quelqu'un a
 *   regardé et ne savait pas », qui sont deux renseignements opposés pour qui cherche
 *   où chercher.
 *
