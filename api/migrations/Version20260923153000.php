 *
 * `destinataire_user_id` (⇢ `core_user`), `sujet_id` (⇢ `tree_person`) et `demande_id`
 * (⇢ `prp_change_request`) sont des identifiants nus : ADR 0002, règle 2. La seule clé
 * étrangère de cette migration est intra-module, de `qst_question_demande` vers
 * `qst_question`.
 *
 * Le risque de trace pendante est nommé plutôt que subi : une `prp_change_request`
 * n'est **jamais supprimée** (ADR 0004 — elle est l'historique de la discussion
 * familiale), refus et caducité compris. Le seul chemin qui l'effacerait est un
 * `DELETE` manuel, et le lien pendant se lirait alors — il ne se réparerait pas.
 *
 * ## Les libellés qui sortent
 *
 * `qst_question.sujet_label` rejoint les colonnes `*_label` du § 0.4 du modèle de
 * données : filtrée comme la personne qu'elle nomme. `qst_question.texte` l'est aussi,
 * et c'est une première — une phrase en français qui **contient** le nom, qu'aucune
 * liste blanche champ par champ n'aurait vue. Voir l'ADR 0008, § Conséquences.
 */
